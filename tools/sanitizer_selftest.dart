int pass = 0;
int fail = 0;

String run(String input) => AIOutputSanitizer.stripMetaPreambles(
  AIOutputSanitizer.stripStateUpdateBlocks(input),
);

void eq(String name, String input, String expected) {
  final String got = run(input);
  if (got == expected) {
    pass++;
    print('PASS  $name');
  } else {
    fail++;
    print('FAIL  $name');
    print('  --- expected ---\n$expected\n  --- got ---\n$got');
  }
}

void has(String name, String input, String needle, {required bool want}) {
  final String got = run(input);
  final bool gotHas = got.contains(needle);
  if (gotHas == want) {
    pass++;
    print('PASS  $name');
  } else {
    fail++;
    print(
      'FAIL  $name (contains "$needle" == $gotHas, want $want)\n--- got ---\n$got',
    );
  }
}

