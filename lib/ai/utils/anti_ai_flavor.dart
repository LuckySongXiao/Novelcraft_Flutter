// 反「AI 味」叙事结构指南 —— 基于 StoryScope 论文的实证发现。
//
// 论文：StoryScope: Investigating idiosyncrasies in AI fiction
//       (arXiv:2604.03136v6, Russell et al., 2026)
//
// 论文用 61,608 篇平行语料（人类 + 5 个 LLM × 同一提示词）× 304 个话语层
// 叙事特征证明：**即使抹掉全部表面风格痕迹，仅凭叙事结构仍能以 93.2%
// macro-F1 区分人/AI**（去除表面 AI 痕迹后只掉 1.6 个百分点）。也就是说，
// 「AI 味」的根子在**话语层叙事选择**而非遣词造句——只查 em-dash、查
// 「delve」这类表面信号是治标。
//
// 论文实证的 5 大结构倾向（AI vs 人类）：
//   1. 主题过度显式：77% 的 AI 故事由叙述者明说主题/教训（人类 52%）；
//      对话更常沦为哲学辩论（59% vs 34%）；用典偏泛泛暗示。
//   2. 因果过于整洁：单线叙事（79% 无支线 vs 57%）、主角驱动结局
//      （69% vs 46%）、因果链紧闭、松散线索被收干净。
//   3. 时间过于线性：人类更爱闪回/闪前/时间跳跃、非线性结构与延迟揭示。
//   4. 感官/身体描写过度：AI 超写身体与感官细节。
//   5. 结局倾向内心和解（47% vs 27%）：人类更能接受歧义/悬而未决。
//
// 这些发现直接转化为写作/编辑 Agent 的**负向约束**（library 常量，测试守护）。
library;

/// 反 AI 味写作指南（拼接进 system prompt 的禁令块）。
///
/// 每条对应论文一个实证维度；措辞按「禁令 + 出路」双段式，
/// 避免 LLM 只收到否定约束后不知所措。
const String kAntiAiFlavorGuidelines = '''
【叙事结构反 AI 味五戒（源自 StoryScope 实证研究）】
一戒点题说教：禁止叙述者直接说出主题或教训，让读者从情节自行推断；对话禁止沦为哲理辩论，人物只说人物会说的话。
二戒单线整洁：至少织入一条不完全收束的支线或留白线索；冲突解决不要全部由主角推动，允许配角改变局面；因果链允许有毛边。
三戒线性叙事：至少使用一次时间跳跃、闪回或倒叙来延迟关键信息揭示，不要按时间顺序平铺。
四戒感官超写：身体感觉与环境感官描写点到为止，同一场景感官细节不超过三处，删去无叙事功能的触觉/温度描写。
五戒和解模板：结局允许歧义、未决或留白，禁止一律以主角内心释怀/领悟收束。
''';

/// 是否把指南拼进 system prompt（拼接函数，便于测试与开关扩展）。
String withAntiAiFlavorGuidelines(String basePrompt, {bool enabled = true}) =>
    enabled ? '$basePrompt\n$kAntiAiFlavorGuidelines' : basePrompt;
